def compute_egm96_degree_variance(max_degree: int = 20) -> list[float]:
    """Compute degree variance (power spectrum) of EGM96.

    sigma_n^2 = sum_{m=0}^n (C_nm^2 + S_nm^2)

    Useful for verifying coefficient correctness and understanding
    the contribution of each degree to the total geoid error.
    """
    C, S = get_egm96_coefficients(max_degree)
    variances = []
    for n in range(2, max_degree + 1):
        var = np.sum(C[n, :n+1]**2 + S[n, :n+1]**2)
        variances.append(math.sqrt(var))
    return variances


